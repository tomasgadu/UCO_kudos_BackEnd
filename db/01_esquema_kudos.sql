    ID_ROL                   UUID           NOT NULL,
    FECHA_REGISTRO           TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_CORREO UNIQUE (CORREO_INSTITUCIONAL),
