-- La auditoría es inmutable (AUD-P-0001): no se permite modificar ni borrar registros.
CREATE FUNCTION fn_auditoria_inmutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Los registros de auditoría no se pueden modificar ni eliminar (AUD-P-0001).';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_auditoria_inmutable BEFORE UPDATE OR DELETE ON REGISTRO_AUDITORIA
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria_inmutable();

